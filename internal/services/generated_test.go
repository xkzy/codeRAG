func TestIncrementalIndexReusesGraphifyRun(t *testing.T) {
	dir := t.TempDir()
	writeFiles(t, dir, map[string]string{
		"go.mod": "module x\n",
		"a.go":   "package x\nfunc A() {}\n",
	})
	app := ApplicationInMemory()
	if _, err := app.Index.IndexRepository("p", dir, true, nil, false); err != nil {
		t.Fatal(err)
	}
	writeFiles(t, dir, map[string]string{"a.go": "package x\nfunc A() {}\nfunc B() {}\n"})
	if _, err := app.Index.IndexRepository("p", dir, true, nil, false); err != nil {
		t.Fatal(err)
	}
	runs, err := app.Graph.FindNodes("GraphifyRun", map[string]any{"project_id": "p"})
	if err != nil {
		t.Fatal(err)
	}
	if len(runs) != 1 {
		t.Fatalf("GraphifyRun nodes = %d, want 1", len(runs))
	}
}

func TestStaleCallEdgesAreRemoved(t *testing.T) {
	dir := t.TempDir()
	writeFiles(t, dir, map[string]string{"a.go": "package x\nfunc A() { B(); C() }\nfunc B() {}\nfunc C() {}\n"})
	app := ApplicationInMemory()
	app.Index.IndexRepository("p", dir, true, nil, false)
	if got := callTargets(t, app, "p", "A"); len(got) != 2 {
		t.Fatalf("setup: %v", got)
	}
	// A no longer calls C.
	writeFiles(t, dir, map[string]string{"a.go": "package x\nfunc A() { B() }\nfunc B() {}\nfunc C() {}\n"})
	app.Index.IndexRepository("p", dir, true, nil, false)
	got := callTargets(t, app, "p", "A")
	if len(got) != 1 || !strings.HasSuffix(got[0], ":B") {
		t.Fatalf("stale A->C edge should be gone: %v", got)
	}
}

func TestStaleCrossFileImplementsEdgeIsRemoved(t *testing.T) {
	dir := t.TempDir()
	writeFiles(t, dir, map[string]string{
		"types.rs": "struct Circle {}\ntrait Shape {}\n",
		"impl.rs":  "impl Shape for Circle {}\n",
	})
	app := ApplicationInMemory()
	app.Index.IndexRepository("p", dir, true, nil, false)
	if got := edgeTargets(app, "p", "IMPLEMENTS", "Circle"); len(got) != 1 {
		t.Fatalf("setup: %v", got)
	}
	writeFiles(t, dir, map[string]string{"impl.rs": "// impl removed\n"})
	app.Index.IndexRepository("p", dir, true, nil, false)
	if got := edgeTargets(app, "p", "IMPLEMENTS", "Circle"); len(got) != 0 {
		t.Fatalf("stale IMPLEMENTS edge survived removal of the impl: %v", got)
	}
}

func TestRemoveEdgesPersists(t *testing.T) {
	dbPath := filepath.Join(t.TempDir(), "g.gob")
	repo, err := graph.NewPersistentRepository(dbPath)
	if err != nil {
		t.Fatal(err)
	}
	a, _ := repo.UpsertNode("Function", map[string]any{"project_id": "p", "qualified_name": "a"}, nil)
	b, _ := repo.UpsertNode("Function", map[string]any{"project_id": "p", "qualified_name": "b"}, nil)
	e1, _ := repo.Link("CALLS", a.ID, b.ID, map[string]any{"source": "x"})
	repo.Link("REFERENCES", a.ID, b.ID, nil)
	if err := repo.RemoveEdges([]string{e1.ID}); err != nil {
		t.Fatal(err)
	}
	repo.Close()
	repo, _ = graph.NewPersistentRepository(dbPath)
	defer repo.Close()
	if n, _ := repo.Neighbors(a.ID, "CALLS", graph.DirOut); len(n) != 0 {
		t.Fatalf("removed edge came back after reload: %d", len(n))
	}
	if n, _ := repo.Neighbors(a.ID, "REFERENCES", graph.DirOut); len(n) != 1 {
		t.Fatalf("unrelated edge lost: %d", len(n))
	}
}

func TestSourceFileNodesCarryTheGeneratedFlag(t *testing.T) {
	app, _ := indexTree(t, map[string]string{"gen.go": "// Code generated by x. DO NOT EDIT.\npackage x\nfunc G() {}\n", "real.go": "package x\nfunc R() {}\n"})
	files, _ := app.Graph.FindNodes("SourceFile", map[string]any{"project_id": "p"})
	got := map[string]bool{}
	for _, f := range files {
		g, _ := f.Properties["generated"].(bool)
		got[strProp(f, "rel_path")] = g
	}
	if !got["gen.go"] || got["real.go"] {
		t.Fatalf("SourceFile generated flags: %v", got)
	}
}
