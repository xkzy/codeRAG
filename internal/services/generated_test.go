func TestIsGenerated(t *testing.T) {
	cases := []struct {
		path, content string
		want          bool
	}{
		{"x.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n", true},
		{"x.py", "# @generated by tool\n", true},
		{"x.ts", "/* auto-generated file */\n", true},
		{"api.pb.go", "package x\n", true},
		{"a_pb2.py", "import x\n", true},
		{"app.min.js", "var a;", true},
		{"x.go", "package x\n// hand written, mentions generated code in passing\nfunc F() {}\n", false},
		{"x.go", strings.Repeat("// filler\n", 30) + "// Code generated by x. DO NOT EDIT.\n", false}, // marker beyond header
		{"main.go", "package main\n", false},
	}
	for _, c := range cases {
		if got := isGenerated(c.path, c.content); got != c.want {
			t.Errorf("isGenerated(%q, %.30q) = %v, want %v", c.path, c.content, got, c.want)
		}
	}
}

func writeFiles(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for name, src := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func TestGeneratedCodeIsFlaggedHiddenFromSearchButStillLinked(t *testing.T) {
	dir := t.TempDir()
	writeFiles(t, dir, map[string]string{
		"real.go": "package x\nfunc UseIt() { ParseThing() }\n",
		"gen.go":  "// Code generated by mockgen. DO NOT EDIT.\npackage x\nfunc ParseThing() {}\n",
	})
	app := ApplicationInMemory()
	if _, err := app.Index.IndexRepository("p", dir, true, nil, false); err != nil {
		t.Fatal(err)
	}
	hidden, _ := app.Code.Search("p", "parse thing", 10, false)
	if len(hidden) != 0 {
		t.Fatalf("generated function should be hidden by default: %v", hidden)
	}
	shown, _ := app.Code.Search("p", "parse thing", 10, true)
	if len(shown) != 1 || shown[0]["generated"] != true {
		t.Fatalf("include_generated should return the flagged function: %v", shown)
	}
	// Calls into generated code are still recorded.
	if got := callTargets(t, app, "p", "UseIt"); len(got) != 1 {
		t.Fatalf("call into generated code lost: %v", got)
	}
}

func TestCommitCacheIsBounded(t *testing.T) {
	commitMu.Lock()
	original := commitCache
	commitCache = map[string]struct {
		sha string
		at  time.Time
	}{}
	commitMu.Unlock()
	t.Cleanup(func() {
		commitMu.Lock()
		commitCache = original
		commitMu.Unlock()
	})
	now := time.Now()
	for i := 0; i < maxCommitCacheEntries+16; i++ {
		commitMu.Lock()
		commitCache[fmt.Sprintf("/repo-%d", i)] = struct {
			sha string
			at  time.Time
		}{at: now.Add(-time.Duration(i) * time.Second)}
		commitMu.Unlock()
	}
	commitMu.Lock()
	pruneCommitCache(now)
	got := len(commitCache)
	commitMu.Unlock()
	if got > maxCommitCacheEntries {
		t.Fatalf("commitCache = %d, want at most %d", got, maxCommitCacheEntries)
	}
}

